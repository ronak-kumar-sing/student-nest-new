// 2. Real-Time Booking & Escrow Status
// -------------------------------------------------------------

export function subscribeToBookingUpdates(
  onUpdate: (booking: { id: string; status: string; totalAmount?: number }) => void,
): () => void {
  if (typeof window === 'undefined') return () => {};

  let unsubscribeFirestore: (() => void) | null = null;

  if (firestore) {
    try {
      const bookingsRef = collection(firestore, 'bookings');
      unsubscribeFirestore = onSnapshot(
        bookingsRef,
        (snapshot) => {
          snapshot.docChanges().forEach((change) => {
            if (change.type === 'modified' || change.type === 'added') {
              const data = change.doc.data();
              onUpdate({ id: change.doc.id, status: data.status, totalAmount: data.totalAmount });
            }
          });
        },
        () => {},
      );
    } catch {
      // silent
    }
  }

  const handleBroadcast = (event: MessageEvent) => {
    if (event.data?.type === 'BOOKING_UPDATE') {
      onUpdate(event.data.payload);
    }
  };

  const handleCustomEvent = (e: any) => {
    onUpdate(e.detail);
  };

  if (broadcastChannel) broadcastChannel.addEventListener('message', handleBroadcast);
  window.addEventListener('firebase_stream_BOOKING_UPDATE', handleCustomEvent);

  return () => {
    if (unsubscribeFirestore) unsubscribeFirestore();
    if (broadcastChannel) broadcastChannel.removeEventListener('message', handleBroadcast);
    window.removeEventListener('firebase_stream_BOOKING_UPDATE', handleCustomEvent);
  };
}

export function broadcastBookingUpdate(booking: {
  id: string;
  status?: string;
  totalAmount?: number;
  reviewed?: boolean;
  [key: string]: any;
}) {
  if (firestore) {
    try {
      const bookingDoc = doc(firestore, 'bookings', booking.id);
      setDoc(bookingDoc, { ...booking, updatedAt: serverTimestamp() }, { merge: true }).catch(() => {});
    } catch {
      // silent
    }
  }
  postToStream('BOOKING_UPDATE', booking);
}

