// 3. Real-Time Listing Reviews
// -------------------------------------------------------------

export function subscribeToListingReviews(
  listingId: string,
  onReviewAdded: (review: any) => void,
): () => void {
  if (!listingId || typeof window === 'undefined') return () => {};

  let unsubscribeFirestore: (() => void) | null = null;

  if (firestore) {
    try {
      const reviewsRef = collection(firestore, 'listings', listingId, 'reviews');
      unsubscribeFirestore = onSnapshot(
        reviewsRef,
        (snapshot) => {
          snapshot.docChanges().forEach((change) => {
            if (change.type === 'added') {
              onReviewAdded({ id: change.doc.id, ...change.doc.data() });
            }
          });
        },
        () => {},
      );
    } catch {
      // silent
    }
  }

  const handleBroadcast = (event: MessageEvent) => {
    if (event.data?.type === 'REVIEW_ADDED' && event.data.payload?.listingId === listingId) {
      onReviewAdded(event.data.payload);
    }
  };

  const handleCustomEvent = (e: any) => {
    if (e.detail?.listingId === listingId) {
      onReviewAdded(e.detail);
    }
  };

  if (broadcastChannel) broadcastChannel.addEventListener('message', handleBroadcast);
  window.addEventListener('firebase_stream_REVIEW_ADDED', handleCustomEvent);

  return () => {
    if (unsubscribeFirestore) unsubscribeFirestore();
    if (broadcastChannel) broadcastChannel.removeEventListener('message', handleBroadcast);
    window.removeEventListener('firebase_stream_REVIEW_ADDED', handleCustomEvent);
  };
}

export function broadcastReview(listingId: string, review: any) {
  if (firestore) {
    try {
      const reviewRef = doc(firestore, 'listings', listingId, 'reviews', review.id || `rev_${Date.now()}`);
      setDoc(reviewRef, { ...review, createdAt: serverTimestamp() }).catch(() => {});
    } catch {
      // silent
    }
  }
  postToStream('REVIEW_ADDED', { ...review, listingId });
}

