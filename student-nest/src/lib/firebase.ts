// Cross-Tab & Real-Time Live Bus (guarantees sub-second sync)
// -------------------------------------------------------------
const REALTIME_CHANNEL_NAME = 'studentnest_firebase_realtime_stream';
const CURRENT_TAB_CLIENT_ID =
  typeof window !== 'undefined'
    ? `tab_${Math.random().toString(36).substring(2, 9)}_${Date.now()}`
    : 'server';

let broadcastChannel: BroadcastChannel | null = null;

if (typeof window !== 'undefined' && 'BroadcastChannel' in window) {
  try {
    broadcastChannel = new BroadcastChannel(REALTIME_CHANNEL_NAME);
  } catch {
    // silent
  }
}

function postToStream(type: string, payload: any) {
  const envelope = {
    type,
    payload,
    originTabId: CURRENT_TAB_CLIENT_ID,
    timestamp: Date.now(),
  };

  if (broadcastChannel) {
    try {
      broadcastChannel.postMessage(envelope);
    } catch {
      // silent
    }
  }
  if (typeof window !== 'undefined') {
    window.dispatchEvent(
      new CustomEvent(`firebase_stream_${type}`, {
        detail: { ...payload, originTabId: CURRENT_TAB_CLIENT_ID },
      }),
    );
  }
}

// -------------------------------------------------------------
// 1. Real-Time Chat & Direct Messaging
// -------------------------------------------------------------

export interface RealtimeChatMessage {
  id: string;
  threadId: string;
  senderId: string;
  senderName: string;
  senderRole: 'student' | 'owner' | 'admin';
  text: string;
  timestamp: string;
  isRead?: boolean;
}

/**
 * Subscribe to live messages for a specific conversation thread.
 * Listens via Cloud Firestore onSnapshot with live fallback.
 */
export function subscribeToMessages(
  threadId: string,
  onMessageReceived: (message: RealtimeChatMessage) => void,
): () => void {
  if (!threadId || typeof window === 'undefined') return () => {};

  let unsubscribeFirestore: (() => void) | null = null;

  if (firestore) {
    try {
      const messagesRef = collection(firestore, 'conversations', threadId, 'messages');
      const q = query(messagesRef, orderBy('createdAt', 'asc'));

      unsubscribeFirestore = onSnapshot(
        q,
        (snapshot) => {
          snapshot.docChanges().forEach((change) => {
            if (change.type === 'added') {
              const data = change.doc.data();
              onMessageReceived({
                id: change.doc.id,
                threadId,
                senderId: data.senderId,
                senderName: data.senderName,
                senderRole: data.senderRole,
                text: data.text,
                timestamp: data.createdAt?.toDate
                  ? data.createdAt.toDate().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
                  : new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
                isRead: data.isRead ?? true,
              });
            }
          });
        },
        (error) => {
          console.warn('[Firebase] Firestore onSnapshot fallback active:', error.message);
        },
      );
    } catch (err: any) {
      console.warn('[Firebase] Listener registration notice:', err.message);
    }
  }

  // Cross-tab broadcast listener - ignore events generated by this tab
  const handleBroadcast = (event: MessageEvent) => {
    if (
      event.data?.type === 'CHAT_MESSAGE' &&
      event.data.payload?.threadId === threadId &&
      event.data.originTabId !== CURRENT_TAB_CLIENT_ID
    ) {
      onMessageReceived(event.data.payload);
    }
  };

  // CustomEvent listener - ignore events triggered by this tab
  const handleCustomEvent = (e: any) => {
    if (e.detail?.threadId === threadId && e.detail?.originTabId !== CURRENT_TAB_CLIENT_ID) {
      onMessageReceived(e.detail);
    }
  };

  if (broadcastChannel) broadcastChannel.addEventListener('message', handleBroadcast);
  window.addEventListener(`firebase_stream_CHAT_MESSAGE`, handleCustomEvent);

  return () => {
    if (unsubscribeFirestore) unsubscribeFirestore();
    if (broadcastChannel) broadcastChannel.removeEventListener('message', handleBroadcast);
    window.removeEventListener(`firebase_stream_CHAT_MESSAGE`, handleCustomEvent);
  };
}

/**
 * Sends a real-time chat message to Firestore and broadcasts to live listeners.
 */
export async function sendRealtimeMessage(
  threadId: string,
  payload: Omit<RealtimeChatMessage, 'id' | 'timestamp'> & { id?: string },
): Promise<RealtimeChatMessage> {
  const messageId = payload.id || `msg_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
  const timestampStr = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

  const completeMessage: RealtimeChatMessage = {
    ...payload,
    id: messageId,
    threadId,
    timestamp: timestampStr,
  };

  if (firestore) {
    try {
      const messageDocRef = doc(firestore, 'conversations', threadId, 'messages', messageId);
      await setDoc(messageDocRef, {
        senderId: payload.senderId,
        senderName: payload.senderName,
        senderRole: payload.senderRole,
        text: payload.text,
        createdAt: serverTimestamp(),
        isRead: false,
      });
    } catch (err: any) {
      console.warn('[Firebase] Firestore write fallback active:', err.message);
    }
  }

  // Broadcast to all other tabs and listeners
  postToStream('CHAT_MESSAGE', completeMessage);

  return completeMessage;
}

